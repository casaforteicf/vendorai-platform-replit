from __future__ import annotations

import asyncio
import os
import shutil
import subprocess
import tempfile
from pathlib import Path
from typing import Annotated

from fastapi import FastAPI, File, Form, Header, HTTPException, UploadFile
from fastapi.responses import FileResponse

APP_NAME = "VendorAI Lip-Sync Worker"
MUSETALK_DIR = Path(os.getenv("MUSETALK_DIR", "/opt/MuseTalk"))
MAX_UPLOAD_BYTES = int(os.getenv("VENDORAI_LIPSYNC_MAX_UPLOAD_BYTES", str(100 * 1024 * 1024)))
MAX_CONCURRENCY = max(1, int(os.getenv("VENDORAI_LIPSYNC_MAX_CONCURRENCY", "1")))
BATCH_SIZE = max(1, int(os.getenv("VENDORAI_LIPSYNC_BATCH_SIZE", "8")))
GPU_ID = int(os.getenv("VENDORAI_LIPSYNC_GPU_ID", "0"))
REQUEST_TIMEOUT_SECONDS = int(os.getenv("VENDORAI_LIPSYNC_TIMEOUT_SECONDS", "840"))
WORKER_SECRET = os.getenv("VENDORAI_LIPSYNC_WORKER_SECRET", "")

MODEL_FILES = (
    "models/musetalkV15/musetalk.json",
    "models/musetalkV15/unet.pth",
    "models/sd-vae/config.json",
    "models/sd-vae/diffusion_pytorch_model.bin",
    "models/whisper/config.json",
    "models/whisper/pytorch_model.bin",
    "models/whisper/preprocessor_config.json",
    "models/dwpose/dw-ll_ucoco_384.pth",
    "models/face-parse-bisent/79999_iter.pth",
    "models/face-parse-bisent/resnet18-5c106cde.pth",
)

app = FastAPI(title=APP_NAME, version="1.0.0")
_gpu_gate = asyncio.Semaphore(MAX_CONCURRENCY)


def _models_ready() -> bool:
    return MUSETALK_DIR.is_dir() and all((MUSETALK_DIR / relative).is_file() for relative in MODEL_FILES)


def _cuda_ready() -> bool:
    try:
        completed = subprocess.run(
            ["nvidia-smi", "-L"],
            capture_output=True,
            text=True,
            timeout=5,
            check=False,
        )
        return completed.returncode == 0 and bool(completed.stdout.strip())
    except Exception:
        return False


def _check_secret(value: str | None) -> None:
    if WORKER_SECRET and value != WORKER_SECRET:
        raise HTTPException(status_code=401, detail="worker secret inválido")


def _safe_suffix(filename: str | None, fallback: str) -> str:
    suffix = Path(filename or "").suffix.lower()
    allowed = {".jpg", ".jpeg", ".png", ".webp", ".wav", ".mp3", ".m4a", ".aac", ".ogg", ".flac"}
    return suffix if suffix in allowed else fallback


async def _save_upload(upload: UploadFile, destination: Path) -> int:
    total = 0
    with destination.open("wb") as handle:
        while True:
            chunk = await upload.read(1024 * 1024)
            if not chunk:
                break
            total += len(chunk)
            if total > MAX_UPLOAD_BYTES:
                raise HTTPException(status_code=413, detail="arquivo excede o limite do worker")
            handle.write(chunk)
    if total == 0:
        raise HTTPException(status_code=422, detail="arquivo vazio")
    return total


def _write_inference_config(path: Path, face_path: Path, audio_path: Path) -> None:
    # YAML kept intentionally minimal; paths are controlled temp paths generated by this worker.
    path.write_text(
        "task_0:\n"
        f"  video_path: {face_path.as_posix()}\n"
        f"  audio_path: {audio_path.as_posix()}\n"
        "  result_name: output.mp4\n",
        encoding="utf-8",
    )


def _run_musetalk(config_path: Path, result_dir: Path, bbox_shift: int) -> Path:
    if not _models_ready():
        raise HTTPException(status_code=503, detail="pesos do MuseTalk 1.5 ainda não estão provisionados")
    if not _cuda_ready():
        raise HTTPException(status_code=503, detail="GPU NVIDIA não disponível para lip-sync")

    # MuseTalk 1.5 uses a fixed bbox shift internally. We map the VendorAI fine adjustment
    # to extra_margin around its documented default of 10 pixels.
    extra_margin = max(0, min(30, 10 + bbox_shift))
    command = [
        "python3",
        "-m",
        "scripts.inference",
        "--inference_config",
        str(config_path),
        "--result_dir",
        str(result_dir),
        "--unet_model_path",
        "models/musetalkV15/unet.pth",
        "--unet_config",
        "models/musetalkV15/musetalk.json",
        "--whisper_dir",
        "models/whisper",
        "--version",
        "v15",
        "--fps",
        "25",
        "--batch_size",
        str(BATCH_SIZE),
        "--gpu_id",
        str(GPU_ID),
        "--extra_margin",
        str(extra_margin),
        "--use_float16",
        "--ffmpeg_path",
        "/usr/bin",
    ]

    env = os.environ.copy()
    env["PYTHONPATH"] = f"{MUSETALK_DIR}:{env.get('PYTHONPATH', '')}".rstrip(":")
    completed = subprocess.run(
        command,
        cwd=MUSETALK_DIR,
        env=env,
        capture_output=True,
        text=True,
        timeout=REQUEST_TIMEOUT_SECONDS,
        check=False,
    )

    output = result_dir / "v15" / "output.mp4"
    if not output.is_file() or output.stat().st_size == 0:
        detail = (completed.stderr or completed.stdout or "MuseTalk não gerou saída").strip()[-1500:]
        raise HTTPException(status_code=500, detail=f"falha no MuseTalk: {detail}")
    return output


@app.get("/health")
def health() -> dict[str, object]:
    return {
        "service": "vendorai-lipsync-worker",
        "engine": "musetalk-1.5",
        "ready": _models_ready() and _cuda_ready(),
        "modelsReady": _models_ready(),
        "cudaReady": _cuda_ready(),
        "maxConcurrency": MAX_CONCURRENCY,
    }


@app.post("/v1/lipsync/generate")
async def generate_lipsync(
    source_face: Annotated[UploadFile, File(...)],
    audio: Annotated[UploadFile, File(...)],
    job_id: Annotated[str, Form(...)],
    bbox_shift: Annotated[int, Form()] = 0,
    x_vendorai_worker_secret: Annotated[str | None, Header()] = None,
):
    _check_secret(x_vendorai_worker_secret)
    if not job_id.strip() or len(job_id) > 128:
        raise HTTPException(status_code=422, detail="job_id inválido")
    bbox_shift = max(-20, min(20, int(bbox_shift)))

    async with _gpu_gate:
        root = Path(tempfile.mkdtemp(prefix="vendorai-lipsync-"))
        try:
            face_path = root / f"source{_safe_suffix(source_face.filename, '.jpg')}"
            audio_path = root / f"audio{_safe_suffix(audio.filename, '.wav')}"
            config_path = root / "inference.yaml"
            result_dir = root / "results"
            result_dir.mkdir(parents=True, exist_ok=True)

            await _save_upload(source_face, face_path)
            await _save_upload(audio, audio_path)
            _write_inference_config(config_path, face_path, audio_path)

            output = await asyncio.to_thread(_run_musetalk, config_path, result_dir, bbox_shift)
            response_copy = root / f"lipsync-{job_id}.mp4"
            shutil.copy2(output, response_copy)

            return FileResponse(
                response_copy,
                media_type="video/mp4",
                filename=f"lipsync-{job_id}.mp4",
                background=None,
            )
        except HTTPException:
            shutil.rmtree(root, ignore_errors=True)
            raise
        except subprocess.TimeoutExpired as exc:
            shutil.rmtree(root, ignore_errors=True)
            raise HTTPException(status_code=504, detail="tempo limite excedido no lip-sync") from exc
        except Exception as exc:
            shutil.rmtree(root, ignore_errors=True)
            raise HTTPException(status_code=500, detail=f"falha interna no lip-sync: {exc}") from exc
