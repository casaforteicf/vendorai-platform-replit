// ─── ARQ COPILOT — Core Types ─────────────────────────────────────────────────
// Architecture only — no external AI. All engines are pure TS functions.

// ════════════════════════════════════════════════════════════════════════════
// MESSAGES
// ════════════════════════════════════════════════════════════════════════════

export type MessageRole   = 'COPILOT' | 'USER' | 'SYSTEM'
export type MessageStatus = 'PENDING' | 'SENT' | 'READ'

export interface CopilotAction {
  label:   string
  value:   string
  variant: 'PRIMARY' | 'SECONDARY' | 'GHOST'
  icon?:   string
}

export interface CopilotSuggestionChip {
  label:  string
  value:  string
}

export interface CopilotMessage {
  id:          string
  role:        MessageRole
  text:        string
  timestamp:   string   // ISO
  actions?:    CopilotAction[]
  chips?:      CopilotSuggestionChip[]
  metadata?:   {
    category?:  string
    confidence?: number    // 0–100
    objectRef?:  string    // id of related project object
  }
  isTyping?:   boolean
}

// ════════════════════════════════════════════════════════════════════════════
// QUESTIONS
// ════════════════════════════════════════════════════════════════════════════

export type QuestionPriority = 'CRITICAL' | 'HIGH' | 'MEDIUM' | 'LOW' | 'OPTIONAL'
export type QuestionType =
  | 'MATERIAL' | 'FABRICANTE' | 'COMPONENTE' | 'FERRAGEM'
  | 'ILUMINACAO' | 'FOTOGRAFIA' | 'OBJETIVO' | 'RENDER'
  | 'BIBLIOTECA' | 'PROMPT' | 'DNA'

export type QuestionStatus = 'PENDING' | 'ANSWERED' | 'SKIPPED' | 'DEFERRED'

export interface CopilotQuestion {
  id:            string
  priority:      QuestionPriority
  type:          QuestionType
  text:          string
  objectRef?:    string    // project object this relates to
  impactPrompt:  number    // 0–100 how much this affects the prompt
  impactRender:  number    // 0–100 how much this affects the render
  impactProject: number    // 0–100 overall project impact
  status:        QuestionStatus
  chips?:        CopilotSuggestionChip[]
}

// ════════════════════════════════════════════════════════════════════════════
// SUGGESTIONS
// ════════════════════════════════════════════════════════════════════════════

export type SuggestionStatus = 'PENDING' | 'ACCEPTED' | 'REJECTED' | 'DEFERRED'

export interface CopilotSuggestion {
  id:       string
  text:     string         // "Posso aplicar componentes Todeschini?"
  why:      string[]       // reasons (explain why)
  category: QuestionType
  impact:   number         // 0–100
  status:   SuggestionStatus
  chips?:   CopilotSuggestionChip[]
}

// ════════════════════════════════════════════════════════════════════════════
// DECISIONS
// ════════════════════════════════════════════════════════════════════════════

export type DecisionActor = 'USUARIO' | 'COPILOT' | 'CATALOGO' | 'BIBLIOTECA' | 'FABRICANTE' | 'SISTEMA' | 'IA'

export interface Decision {
  id:          string
  timestamp:   string      // ISO
  actor:       DecisionActor
  description: string
  objectRef?:  string
  accepted?:   boolean
}

// ════════════════════════════════════════════════════════════════════════════
// WORKFLOWS
// ════════════════════════════════════════════════════════════════════════════

export type WorkflowId =
  | 'INITIAL' | 'REVISION' | 'CATALOG' | 'MATERIAL_SELECTION' | 'RENDER_PREP'

export type WorkflowStepStatus = 'PENDING' | 'IN_PROGRESS' | 'DONE' | 'SKIPPED'

export interface WorkflowStep {
  id:          string
  label:       string
  icon:        string
  status:      WorkflowStepStatus
  description: string
}

export interface Workflow {
  id:       WorkflowId
  name:     string
  steps:    WorkflowStep[]
  current:  number   // index of current step
}

// ════════════════════════════════════════════════════════════════════════════
// SMART TASKS
// ════════════════════════════════════════════════════════════════════════════

export type TaskStatus = 'PENDING' | 'IN_PROGRESS' | 'DONE' | 'BLOCKED'
export type TaskPriority = 'CRITICAL' | 'HIGH' | 'MEDIUM' | 'LOW'

export interface SmartTask {
  id:         string
  label:      string
  priority:   TaskPriority
  status:     TaskStatus
  category:   QuestionType
  objectRef?: string
  autoGen:    boolean    // generated by system vs user-added
}

// ════════════════════════════════════════════════════════════════════════════
// CHECKLIST
// ════════════════════════════════════════════════════════════════════════════

export type ChecklistArea = 'PROJETO' | 'VISION' | 'OBJETOS' | 'MATERIAIS' | 'BIBLIOTECA' | 'PROMPT' | 'RENDER' | 'REVIEW'
export type ChecklistStatus = 'DONE' | 'PARTIAL' | 'MISSING'

export interface ChecklistItem {
  area:    ChecklistArea
  icon:    string
  label:   string
  status:  ChecklistStatus
  score:   number   // 0–100
  detail?: string
}

// ════════════════════════════════════════════════════════════════════════════
// PROJECT HEALTH
// ════════════════════════════════════════════════════════════════════════════

export type ProjectHealth = 'EXCELENTE' | 'BOM' | 'REGULAR' | 'NECESSITA_AJUSTES'

export interface ProjectHealthResult {
  health:   ProjectHealth
  score:    number   // 0–100
  reasons:  string[]
  alerts:   string[]
}

// ════════════════════════════════════════════════════════════════════════════
// COPILOT STATE
// ════════════════════════════════════════════════════════════════════════════

export interface CopilotState {
  messages:     CopilotMessage[]
  questions:    CopilotQuestion[]
  suggestions:  CopilotSuggestion[]
  decisions:    Decision[]
  workflow:     Workflow
  tasks:        SmartTask[]
  checklist:    ChecklistItem[]
  health:       ProjectHealthResult
  progress:     number       // 0–100
  renderReady:  number       // 0–100
}
