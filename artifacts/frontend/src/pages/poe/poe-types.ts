export const POE_OPPORTUNITY_TYPES = [
  "missing_item", "missing_supplier", "incompatible_item",
  "cross_sell", "up_sell", "missing_category", "substitutable_item",
] as const;

export const POE_OPPORTUNITY_STATUS = [
  "detected", "analyzing", "ready", "quoted", "closed", "dismissed",
] as const;

export const POE_QUOTATION_STATUS = [
  "draft", "sent", "received", "comparing", "approved", "rejected", "expired",
] as const;

export type PoeOpportunityType   = typeof POE_OPPORTUNITY_TYPES[number];
export type PoeOpportunityStatus = typeof POE_OPPORTUNITY_STATUS[number];
export type PoeQuotationStatus   = typeof POE_QUOTATION_STATUS[number];

export interface PoeOpportunity {
  id:             string;
  tenantId:       string;
  projectId:      string | null;
  projectName:    string | null;
  type:           string;
  status:         string;
  priority:       number;
  title:          string;
  description:    string | null;
  environment:    string | null;
  category:       string | null;
  itemRef:        string | null;
  justification:  string | null;
  technicalBasis: string[];
  tags:           string[];
  aiGenerated:    boolean;
  dismissed:      boolean;
  createdAt:      Date;
  updatedAt:      Date;
}

export interface PoeRecommendation {
  id:               string;
  opportunityId:    string;
  vcnCompanyId:     string | null;
  vcnProductId:     string | null;
  companyName:      string | null;
  productName:      string | null;
  productSku:       string | null;
  scoreTechnical:   number | null;
  scoreAesthetic:   number | null;
  scoreDimensional: number | null;
  scoreFinancial:   number | null;
  scoreRegional:    number | null;
  scoreLeadTime:    number | null;
  scoreOverall:     number | null;
  justification:    string;
  advantages:       string[];
  caveats:          string[];
  estimatedPrice:   string | null;
  priceUnit:        string | null;
  leadTimeDays:     number | null;
  inStock:          boolean | null;
  region:           string | null;
  selected:         boolean;
  dismissed:        boolean;
  rank:             number;
  createdAt:        Date;
  updatedAt:        Date;
}

export interface QuotationItem {
  opportunityId: string;
  productId?:    string;
  productName:   string;
  quantity?:     number;
  unit?:         string;
  notes?:        string;
}

export interface PoeQuotationRequest {
  id:            string;
  tenantId:      string;
  projectId:     string | null;
  projectName:   string | null;
  items:         QuotationItem[];
  vcnCompanyId:  string | null;
  companyName:   string | null;
  contactEmail:  string | null;
  contactPhone:  string | null;
  region:        string | null;
  deadline:      Date | null;
  notes:         string | null;
  attachments:   string[];
  status:        string;
  leadId:        string | null;
  opportunityId: string | null;
  activityId:    string | null;
  sentAt:        Date | null;
  createdAt:     Date;
  updatedAt:     Date;
}

// Opportunity matrix row (generated by engine)
export interface OpportunityMatrixRow {
  environment: string;
  category:    string;
  status:      "covered" | "partial" | "missing";
  opportunities: PoeOpportunity[];
}
