import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { useMemo, useState } from "react";
import { useAuth } from "@/contexts/AuthContext";
import { SidebarLayout } from "@/components/layout/SidebarLayout";
import { Button } from "@/components/ui/button";
import { Dialog, DialogContent, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Bot, CalendarDays, CheckCircle2, ChevronDown, ChevronRight, Clock, Coins, Loader2, TrendingUp, UserRound } from "lucide-react";

type CommissionStatus = "pendente" | "aprovado" | "pago" | "cancelado";
type SaleItem = { nome: string; quantidade: number; valorUnitario: number; sku?: string; produtoId?: string };
type CommissionDetail = { produtoId: string | null; sku: string | null; nome: string; quantidade: number; valorUnitarioCents: number; valorBaseCents: number; percentual: number; valorComissaoCents: number; promocional: boolean };
type Sale = {
  id: string; dealId: string | null; title: string; items: SaleItem[]; saleDate: string;
  totalCents: number; autoGenerated: boolean; commissionId: string | null;
  commissionStatus: CommissionStatus | null; commissionCents: number; commissionBaseCents: number;
  commissionDetails: CommissionDetail[] | null; commissionNotes: string | null; paidAt: string | null;
};
type Seller = {
  id: string; kind: "human" | "ai"; name: string; email: string; active: boolean;
  salesCount: number; salesTotalCents: number; commissionTotalCents: number;
  pendingCents: number; approvedCents: number; paidCents: number; sales: Sale[];
};
type Overview = { period: { dateFrom: string | null; dateTo: string | null }; sellers: Seller[] };

const money = (cents: number) => new Intl.NumberFormat("pt-BR", { style: "currency", currency: "BRL" }).format(cents / 100);
const date = (iso: string) => new Date(iso).toLocaleDateString("pt-BR");
const statusLabel: Record<CommissionStatus, string> = { pendente: "Pendente", aprovado: "Aprovado", pago: "Pago", cancelado: "Cancelado" };

function initialPeriod() {
  const now = new Date();
  const first = new Date(now.getFullYear(), now.getMonth(), 1);
  const format = (value: Date) => `${value.getFullYear()}-${String(value.getMonth() + 1).padStart(2, "0")}-${String(value.getDate()).padStart(2, "0")}`;
  return { from: format(first), to: format(now) };
}

function StatusBadge({ status }: { status: CommissionStatus | null }) {
  if (!status) return <span className="rounded-full border px-2 py-0.5 text-xs text-gray-500">Sem comissão</span>;
  const colors = { pendente: "bg-yellow-50 text-yellow-800 border-yellow-200", aprovado: "bg-blue-50 text-blue-800 border-blue-200", pago: "bg-green-50 text-green-800 border-green-200", cancelado: "bg-red-50 text-red-800 border-red-200" };
  return <span className={`rounded-full border px-2 py-0.5 text-xs font-medium ${colors[status]}`}>{statusLabel[status]}</span>;
}

export default function ComissoesVendedor({ embedded = false }: { embedded?: boolean }) {
  const { user, token } = useAuth();
  const queryClient = useQueryClient();
  const initial = useMemo(initialPeriod, []);
  const [dateFrom, setDateFrom] = useState(initial.from);
  const [dateTo, setDateTo] = useState(initial.to);
  const [openSeller, setOpenSeller] = useState<string | null>(null);
  const [openSale, setOpenSale] = useState<string | null>(null);
  const [editingSale, setEditingSale] = useState<Sale | null>(null);
  const [editStatus, setEditStatus] = useState<CommissionStatus>("pendente");
  const [editObs, setEditObs] = useState("");
  const tenantId = user?.tenantId;
  const isAdmin = user?.platformRole === "super_admin" || user?.platformRole === "tenant_admin" || user?.userFunction === "administrador";
  const headers = { Authorization: `Bearer ${token}`, "Content-Type": "application/json" };

  const { data, isLoading } = useQuery<Overview>({
    queryKey: ["seller-commissions-by-seller", tenantId, dateFrom, dateTo],
    enabled: !!tenantId && !!token,
    queryFn: async () => {
      const query = new URLSearchParams({ dateFrom, dateTo });
      const response = await fetch(`/api/tenants/${tenantId}/seller-commissions/by-seller?${query}`, { headers });
      if (!response.ok) throw new Error("Erro ao carregar vendas e comissões");
      return response.json();
    },
  });

  const sellers = data?.sellers ?? [];
  const totals = sellers.reduce((acc, seller) => ({
    pending: acc.pending + seller.pendingCents,
    approved: acc.approved + seller.approvedCents,
    paid: acc.paid + seller.paidCents,
    total: acc.total + seller.commissionTotalCents,
  }), { pending: 0, approved: 0, paid: 0, total: 0 });

  const updateMutation = useMutation({
    mutationFn: async () => {
      if (!editingSale?.commissionId) return;
      const response = await fetch(`/api/tenants/${tenantId}/seller-commissions/${editingSale.commissionId}`, { method: "PATCH", headers, body: JSON.stringify({ status: editStatus, observacoes: editObs }) });
      if (!response.ok) throw new Error("Erro ao atualizar comissão");
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ["seller-commissions-by-seller", tenantId] });
      setEditingSale(null);
    },
  });

  const cards = [
    ["Total pendente", totals.pending, Clock, "bg-yellow-50 text-yellow-700 border-yellow-100"],
    ["Total aprovado", totals.approved, TrendingUp, "bg-blue-50 text-blue-700 border-blue-100"],
    ["Total pago", totals.paid, CheckCircle2, "bg-green-50 text-green-700 border-green-100"],
    ["Total geral", totals.total, Coins, "bg-purple-50 text-purple-700 border-purple-100"],
  ] as const;

  const content = <div className={embedded ? "space-y-5" : "mx-auto max-w-6xl space-y-5 p-4 sm:p-6"}>
    <div className="flex flex-col gap-4 sm:flex-row sm:items-end sm:justify-between">
      <div className="flex items-start gap-3">
        <div className="rounded-lg bg-indigo-100 p-2"><Coins className="h-6 w-6 text-indigo-600" /></div>
        <div><h1 className="text-2xl font-bold text-gray-900">{isAdmin ? "Comissões de vendedores" : "Minhas comissões"}</h1><p className="text-sm text-gray-500">Vendedores, vendas, itens e regras aplicadas em um só lugar</p></div>
      </div>
      <div className="flex flex-wrap items-end gap-2 rounded-xl border bg-white p-3">
        <CalendarDays className="mb-2 h-4 w-4 text-gray-500" />
        <label className="text-xs text-gray-500">De<input type="date" value={dateFrom} onChange={(event) => setDateFrom(event.target.value)} className="mt-1 block rounded-md border px-2 py-1.5 text-sm text-gray-800" /></label>
        <label className="text-xs text-gray-500">Até<input type="date" value={dateTo} onChange={(event) => setDateTo(event.target.value)} className="mt-1 block rounded-md border px-2 py-1.5 text-sm text-gray-800" /></label>
      </div>
    </div>

    <div className="grid grid-cols-2 gap-3 md:grid-cols-4">{cards.map(([label, value, Icon, style]) => <div key={label} className={`rounded-xl border p-4 ${style}`}><div className="mb-2 flex items-center justify-between"><span className="text-xs font-medium">{label}</span><Icon className="h-4 w-4" /></div><p className="text-xl font-bold">{money(value)}</p></div>)}</div>

    <div className="overflow-hidden rounded-xl border bg-white shadow-sm">
      <div className="border-b bg-gray-50 px-4 py-3"><p className="font-medium text-gray-800">Equipe comercial</p><p className="text-xs text-gray-500">{sellers.length} vendedor(es), incluindo vendas autônomas da IA</p></div>
      {isLoading ? <div className="flex justify-center py-16"><Loader2 className="h-6 w-6 animate-spin text-gray-400" /></div> : sellers.map((seller) => {
        const expanded = openSeller === seller.id;
        return <div key={seller.id} className="border-b last:border-0">
          <button className="grid w-full grid-cols-[1fr_auto] gap-3 px-4 py-4 text-left hover:bg-gray-50 md:grid-cols-[1.5fr_.6fr_.8fr_.8fr_auto] md:items-center" onClick={() => setOpenSeller(expanded ? null : seller.id)}>
            <span className="flex min-w-0 items-center gap-3">{seller.kind === "ai" ? <Bot className="h-9 w-9 rounded-full bg-purple-100 p-2 text-purple-700" /> : <UserRound className="h-9 w-9 rounded-full bg-gray-100 p-2 text-gray-600" />}<span className="min-w-0"><span className="block truncate font-semibold">{seller.name}</span><span className="block truncate text-xs text-gray-500">{seller.email}{!seller.active ? " • inativo" : ""}</span></span></span>
            <span className="md:hidden">{expanded ? <ChevronDown /> : <ChevronRight />}</span>
            <span className="hidden text-sm md:block"><b>{seller.salesCount}</b><small className="block text-gray-500">vendas</small></span>
            <span className="hidden text-sm md:block"><b>{money(seller.salesTotalCents)}</b><small className="block text-gray-500">vendido</small></span>
            <span className="hidden text-sm text-green-700 md:block"><b>{money(seller.commissionTotalCents)}</b><small className="block text-gray-500">comissão</small></span>
            <span className="hidden md:block">{expanded ? <ChevronDown /> : <ChevronRight />}</span>
          </button>
          {expanded && <div className="bg-slate-50 px-3 py-3 sm:px-6">
            <div className="mb-3 grid grid-cols-3 gap-2 text-center text-xs md:hidden"><div><b className="block text-sm">{seller.salesCount}</b>vendas</div><div><b className="block text-sm">{money(seller.salesTotalCents)}</b>vendido</div><div><b className="block text-sm text-green-700">{money(seller.commissionTotalCents)}</b>comissão</div></div>
            {seller.sales.length === 0 ? <p className="py-6 text-center text-sm text-gray-500">Nenhuma venda neste período.</p> : seller.sales.map((sale) => {
              const saleExpanded = openSale === sale.id;
              const details = sale.commissionDetails?.length ? sale.commissionDetails : sale.items.map((item) => ({ ...item, valorUnitarioCents: Math.round(item.valorUnitario * 100), valorBaseCents: Math.round(item.valorUnitario * item.quantidade * 100), percentual: 0, valorComissaoCents: 0, promocional: false, produtoId: item.produtoId ?? null, sku: item.sku ?? null }));
              return <div key={sale.id} className="mb-2 overflow-hidden rounded-lg border bg-white last:mb-0">
                <button className="grid w-full grid-cols-[1fr_auto] gap-2 px-3 py-3 text-left sm:grid-cols-[1.5fr_.7fr_.7fr_.7fr_auto] sm:items-center" onClick={() => setOpenSale(saleExpanded ? null : sale.id)}><span><b className="block text-sm">{sale.title}</b><small className="text-gray-500">{date(sale.saleDate)}{sale.autoGenerated ? " • originada pela IA" : ""}</small></span><span className="sm:hidden">{saleExpanded ? <ChevronDown /> : <ChevronRight />}</span><span className="hidden text-sm sm:block">{details.length} item(ns)</span><span className="hidden text-sm sm:block">{money(sale.totalCents)}</span><span className="hidden sm:block"><StatusBadge status={sale.commissionStatus} /></span><span className="hidden sm:block">{saleExpanded ? <ChevronDown /> : <ChevronRight />}</span></button>
                {saleExpanded && <div className="border-t p-3"><div className="mb-3 flex flex-wrap items-center justify-between gap-2 sm:hidden"><b>{money(sale.totalCents)}</b><StatusBadge status={sale.commissionStatus} /></div><div className="overflow-x-auto"><table className="w-full min-w-[620px] text-sm"><thead className="text-left text-xs text-gray-500"><tr><th className="pb-2">Item</th><th>Qtd.</th><th>Valor unitário</th><th>Base</th><th>Regra aplicada</th><th className="text-right">Comissão</th></tr></thead><tbody>{details.map((item, index) => <tr key={`${item.produtoId ?? item.sku ?? item.nome}-${index}`} className="border-t"><td className="py-2 font-medium">{item.nome}{item.promocional && <span className="ml-2 rounded bg-orange-50 px-1.5 py-0.5 text-[10px] text-orange-700">Promocional</span>}</td><td>{item.quantidade}</td><td>{money(item.valorUnitarioCents)}</td><td>{money(item.valorBaseCents)}</td><td>{Number(item.percentual).toLocaleString("pt-BR")}%</td><td className="text-right font-semibold text-green-700">{money(item.valorComissaoCents)}</td></tr>)}</tbody></table></div><div className="mt-3 flex flex-wrap items-center justify-between gap-2 border-t pt-3"><p className="text-sm text-gray-600">Base: <b>{money(sale.commissionBaseCents || sale.totalCents)}</b> · Comissão: <b className="text-green-700">{money(sale.commissionCents)}</b></p>{isAdmin && sale.commissionId && <Button variant="outline" size="sm" onClick={() => { setEditingSale(sale); setEditStatus(sale.commissionStatus ?? "pendente"); setEditObs(sale.commissionNotes ?? ""); }}>Atualizar comissão</Button>}</div></div>}
              </div>;
            })}
          </div>}
        </div>;
      })}
    </div>
  </div>;

  const dialog = <Dialog open={!!editingSale} onOpenChange={(open) => !open && setEditingSale(null)}><DialogContent className="sm:max-w-md"><DialogHeader><DialogTitle>Atualizar comissão</DialogTitle></DialogHeader><div className="space-y-4"><Select value={editStatus} onValueChange={(value) => setEditStatus(value as CommissionStatus)}><SelectTrigger><SelectValue /></SelectTrigger><SelectContent>{Object.entries(statusLabel).map(([value, label]) => <SelectItem key={value} value={value}>{label}</SelectItem>)}</SelectContent></Select><textarea className="w-full resize-none rounded-md border p-2 text-sm" rows={3} value={editObs} onChange={(event) => setEditObs(event.target.value)} placeholder="Observações sobre a comissão" /><div className="flex justify-end gap-2"><Button variant="outline" onClick={() => setEditingSale(null)}>Cancelar</Button><Button disabled={updateMutation.isPending} onClick={() => updateMutation.mutate()}>{updateMutation.isPending ? <Loader2 className="h-4 w-4 animate-spin" /> : "Salvar"}</Button></div></div></DialogContent></Dialog>;
  return embedded ? <>{content}{dialog}</> : <SidebarLayout>{content}{dialog}</SidebarLayout>;
}
