export function featureForDate(date = new Date()): VendorFeature {
  const start = new Date(date.getFullYear(), 0, 0);
  const dayOfYear = Math.floor((date.getTime() - start.getTime()) / 86_400_000);
  return VENDOR_FEATURES[dayOfYear % VENDOR_FEATURES.length]!;
}
