describe("GET propostas — same-tenant responsible isolation", () => {
  const memberToken = makeToken(TENANT_A, "member");

  beforeEach(() => {
    vi.clearAllMocks();
  });

  it("returns 403 for an individual proposal owned by another lead responsible", async () => {
    const proposal = { id: "proposal-other-owner", tenantId: TENANT_A, leadId: "lead-other", dealId: null, titulo: "Privada", status: "rascunho", itens: [] };
    mockDbSelect
      .mockReturnValueOnce({ from: vi.fn().mockReturnValue({ where: vi.fn().mockResolvedValue([proposal]) }) })
      .mockReturnValueOnce({ from: vi.fn().mockReturnValue({ where: vi.fn().mockReturnValue({ limit: vi.fn().mockResolvedValue([{ assignedTo: "another-user" }]) }) }) });

    const res = await request(app)
      .get("/api/propostas/proposal-other-owner")
      .set("Authorization", `Bearer ${memberToken}`);

    expect(res.status).toBe(403);
    expect(res.body).toMatchObject({ error: expect.stringContaining("proposal") });
  });

  it("filters same-tenant proposal list by lead/deal responsibility for non-admin users", async () => {
    const ownUserId = `user-${TENANT_A}`;
    const rows = [
      { id: "p-own", tenantId: TENANT_A, leadId: "lead-own", dealId: null, titulo: "Minha", status: "rascunho" },
      { id: "p-other", tenantId: TENANT_A, leadId: "lead-other", dealId: null, titulo: "Outra", status: "rascunho" },
    ];
    const orderBy = vi.fn().mockResolvedValue(rows);
    mockDbSelect
      .mockReturnValueOnce({ from: vi.fn().mockReturnValue({ where: vi.fn().mockReturnValue({ orderBy }) }) })
      .mockReturnValueOnce({ from: vi.fn().mockReturnValue({ where: vi.fn().mockReturnValue({ limit: vi.fn().mockResolvedValue([{ assignedTo: ownUserId }]) }) }) })
      .mockReturnValueOnce({ from: vi.fn().mockReturnValue({ where: vi.fn().mockReturnValue({ limit: vi.fn().mockResolvedValue([{ assignedTo: "another-user" }]) }) }) });

    const res = await request(app)
      .get(`/api/tenants/${TENANT_A}/propostas`)
      .set("Authorization", `Bearer ${memberToken}`);

    expect(res.status).toBe(200);
    expect(res.body.map((p: { id: string }) => p.id)).toEqual(["p-own"]);
  });
});

