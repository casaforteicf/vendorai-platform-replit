import { routeSignals, type BusinessSignal, type RoutedOpportunity } from './intelligence-routing';

export interface BusinessObserverSnapshot {
  tenantId: string;
  generatedAt: string;
  signals: BusinessSignal[];
  opportunities: RoutedOpportunity[];
  byDomain: Record<string, number>;
  byTarget: Record<string, number>;
  criticalCount: number;
  highCount: number;
  topOpportunities: RoutedOpportunity[];
}

const PRIORITY_WEIGHT: Record<RoutedOpportunity['priority'], number> = {
  low: 1,
  medium: 2,
  high: 3,
  critical: 4,
};

/**
 * Business Observer is read-only. It aggregates signals generated by canonical
 * modules and routes them into opportunities; it never mutates CRM, Marketing,
 * Finance or Operations directly.
 */
export function buildBusinessObserverSnapshot(
  tenantId: string,
  signals: BusinessSignal[],
): BusinessObserverSnapshot {
  const tenantSignals = signals.filter((signal) => signal.tenantId === tenantId);
  const opportunities = routeSignals(tenantSignals);
  const byDomain: Record<string, number> = {};
  const byTarget: Record<string, number> = {};

  for (const signal of tenantSignals) {
    byDomain[signal.domain] = (byDomain[signal.domain] ?? 0) + 1;
  }
  for (const opportunity of opportunities) {
    byTarget[opportunity.target] = (byTarget[opportunity.target] ?? 0) + 1;
  }

  const topOpportunities = [...opportunities]
    .sort((a, b) => PRIORITY_WEIGHT[b.priority] - PRIORITY_WEIGHT[a.priority])
    .slice(0, 10);

  return {
    tenantId,
    generatedAt: new Date().toISOString(),
    signals: tenantSignals,
    opportunities,
    byDomain,
    byTarget,
    criticalCount: opportunities.filter((item) => item.priority === 'critical').length,
    highCount: opportunities.filter((item) => item.priority === 'high').length,
    topOpportunities,
  };
}
