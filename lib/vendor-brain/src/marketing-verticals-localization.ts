function translateOperationalText(value: string): string {
  let translated = value
  for (const [pt, es] of REPLACEMENTS) translated = translated.split(pt).join(es)
  return translated
}

function translateList(values: string[]): string[] {
  return values.map(translateOperationalText)
}

export function localizeMarketingVertical(
  profile: MarketingVerticalProfile,
  locale: MarketingVerticalLocale | string,
): MarketingVerticalProfile {
  if (!locale.startsWith('es')) return profile

  const copy = ES_COPY[profile.id]
  const name = copy?.name ?? translateOperationalText(profile.name)

  return {
    ...profile,
    name,
    decisionMakers: translateList(profile.decisionMakers),
    corePain: copy?.corePain ?? translateOperationalText(profile.corePain),
    promise: copy?.promise ?? translateOperationalText(profile.promise),
    journey: translateList(profile.journey),
    pipeline: translateList(profile.pipeline),
    priorityAgents: translateList(profile.priorityAgents),
    lp: {
      ...profile.lp,
      heroEyebrow: `VendorAI para ${name}`,
      headline: copy?.headline ?? translateOperationalText(profile.lp.headline),
      subheadline: copy?.subheadline ?? translateOperationalText(profile.lp.subheadline),
      primaryCta: copy?.primaryCta ?? 'Probar 5 días gratis',
      secondaryCta: 'Ver demostración',
      painMap: translateList(profile.lp.painMap),
      timeline: profile.lp.timeline.map((step) => ({
        ...step,
        label: translateOperationalText(step.label),
        description: step.description ? translateOperationalText(step.description) : undefined,
      })),
      faq: [
        `¿VendorAI funciona para ${name.toLowerCase()}?`,
        '¿Necesito cambiar mis canales actuales?',
        '¿La IA puede acompañar oportunidades automáticamente?',
        '¿Puedo medir qué campaña generó la venta?',
        '¿Cómo funciona la prueba de 5 días?',
      ],
    },
    revenueScout: {
      signals: translateList(profile.revenueScout.signals),
      nextBestActions: translateList(profile.revenueScout.nextBestActions),
    },
    creativeAngles: translateList(profile.creativeAngles),
    kpis: translateList(profile.kpis),
  }
}

export function localizeMarketingVerticals(
  profiles: MarketingVerticalProfile[],
  locale: MarketingVerticalLocale | string,
): MarketingVerticalProfile[] {
  return locale.startsWith('es') ? profiles.map((profile) => localizeMarketingVertical(profile, locale)) : profiles
}

export function assertSpanishMarketingVerticalCoverage(profiles: MarketingVerticalProfile[]): true {
  const missing = profiles.filter((profile) => !ES_COPY[profile.id]).map((profile) => profile.id)
  if (missing.length > 0) throw new Error(`Missing Spanish vertical copy: ${missing.join(', ')}`)
  return true
}
